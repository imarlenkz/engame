/** Splits a sentence into lower-case word tokens. */
export function sentenceTokens(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/[^a-z' ]/g, ' ')
    .split(/\s+/)
    .filter(Boolean);
}
